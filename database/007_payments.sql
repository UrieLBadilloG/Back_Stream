CREATE TABLE IF NOT EXISTS payments (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  course_id BIGINT UNSIGNED NOT NULL,
  provider ENUM('mercadopago') NOT NULL DEFAULT 'mercadopago',
  preference_id VARCHAR(100) NULL,
  checkout_url VARCHAR(512) NULL,
  mp_payment_id BIGINT UNSIGNED NULL,
  external_reference VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  status_detail VARCHAR(80) NULL,
  amount_cents INT UNSIGNED NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  currency CHAR(3) NOT NULL,
  payer_email VARCHAR(254) NULL,
  raw_status_payload JSON NULL,
  needs_review TINYINT(1) NOT NULL DEFAULT 0,
  review_reason VARCHAR(80) NULL,
  enrollment_id BIGINT UNSIGNED NULL,
  approved_at TIMESTAMP NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_payments_external_reference (external_reference),
  UNIQUE KEY uq_payments_mp_payment (mp_payment_id),
  KEY idx_payments_user (user_id, created_at),
  KEY idx_payments_course (course_id, status),
  KEY idx_payments_status (status, created_at),
  KEY idx_payments_review (needs_review, created_at),
  CONSTRAINT fk_payments_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_payments_course FOREIGN KEY (course_id) REFERENCES courses (id),
  CONSTRAINT fk_payments_enrollment FOREIGN KEY (enrollment_id) REFERENCES enrollments (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
